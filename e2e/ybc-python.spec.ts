// YB5A-R2 / R3: Copy and Download never export older Python than the blocks on screen, and a refused
// clipboard falls back to a selected source (plan §17.3). The edits below are made in Blockly itself and
// the export is clicked at once, well inside the 250 ms save and 250 ms regeneration delays.

const blocklyPanel = (page: Page) => page.getByTestId('blockly-panel');

/**
 * Types a new value into the number block showing `current`, as a learner does, and returns without waiting for
 * any save. It does wait for Blockly's editor to open before typing (on a busy machine it opens late, and the keys
 * would go elsewhere) and to close on Enter, which commits the value at once.
 */
async function editNumber(page: Page, current: string, next: string) {
  const editor = page.locator('.blocklyWidgetDiv input.blocklyHtmlInput');
  await blocklyPanel(page).locator('.blocklyEditableField .blocklyText', { hasText: new RegExp(`^${current}$`) }).first().click();
  await expect(editor).toBeVisible();
  // Select all the field's text: Cmd+A on macOS, Ctrl+A elsewhere (Control+A only moves the caret on macOS).
  await page.keyboard.press('ControlOrMeta+A');
  await page.keyboard.type(next);
  await page.keyboard.press('Enter');
  await expect(editor).toBeHidden();
}

async function downloadedText(page: Page) {
  const [download] = await Promise.all([page.waitForEvent('download', { timeout: 5000 }), page.getByRole('button', { name: 'Download' }).click()]);
  const chunks: Buffer[] = [];
  for await (const chunk of await download.createReadStream()) {
    chunks.push(chunk as Buffer);
  }
  return Buffer.concat(chunks).toString('utf8');
}

/** True when a click on Download starts a download within a second. */
async function downloadStarts(page: Page) {
  const started = page.waitForEvent('download', { timeout: 1000 }).then(() => true, () => false);
  await page.getByRole('button', { name: 'Download' }).click();
  return started;
}

test.describe('export is never older than the blocks on screen', () => {
  test.beforeEach(async ({ page, context }) => {
    await context.grantPermissions(['clipboard-read', 'clipboard-write']);
    await openProject(page, project(program([print(num(1))])));
    await expect(source(page)).toContainText('print(1)');
  });

  test('Download right after an invalid edit (1 to 1.5) exports nothing, and the panel says why', async ({ page }) => {
    await editNumber(page, '1', '1.5');
    expect(await downloadStarts(page)).toBe(false);
    await expect(page.getByTestId('python-diagnostics')).toBeVisible();
    await expect(source(page)).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'Download' })).toBeDisabled();
    await expect(page.getByRole('button', { name: 'Copy' })).toBeDisabled();
  });

  test('Copy right after an invalid edit leaves the clipboard alone', async ({ page }) => {
    await page.evaluate(() => navigator.clipboard.writeText('SENTINEL'));
    await editNumber(page, '1', '1.5');
    await page.getByRole('button', { name: 'Copy' }).click();
    await expect(page.getByTestId('python-diagnostics')).toBeVisible();
    expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('SENTINEL');
  });

  test('Download right after a valid edit (1 to 2) exports print(2), never print(1)', async ({ page }) => {
    await editNumber(page, '1', '2');
    const saved = await downloadedText(page);
    expect(saved).toContain('print(2)');
    expect(saved).not.toContain('print(1)');
    await expect(source(page)).toContainText('print(2)');
  });

  test('Copy right after a valid edit (1 to 2) copies print(2), never print(1)', async ({ page }) => {
    await editNumber(page, '1', '2');
    await page.getByRole('button', { name: 'Copy' }).click();
    await expect(page.getByRole('button', { name: 'Copied' })).toBeVisible();
    const copied = await page.evaluate(() => navigator.clipboard.readText());
    expect(copied).toContain('print(2)');
    expect(copied).not.toContain('print(1)');
  });

  test('an invalid edit that is fixed again exports the fixed program', async ({ page }) => {
    await editNumber(page, '1', '1.5');
    expect(await downloadStarts(page)).toBe(false);
    await editNumber(page, '1.5', '3');
    await expect(source(page)).toContainText('print(3)');
    expect(await downloadedText(page)).toContain('print(3)');
  });
});

test('when the clipboard is refused, the source is selected and the copy key is explained, with no false Copied', async ({ page }) => {
  await openProject(page, project(program([print(text('héllo'))])));
  await expect(source(page)).toContainText("print('héllo')");
  await page.evaluate(() => {
    Object.defineProperty(navigator.clipboard, 'writeText', { value: () => Promise.reject(new Error('denied')), configurable: true });
  });

  await page.getByRole('button', { name: 'Copy' }).click();

  // The app names the copy key of the platform the browser reports (PythonPanel's copyKey): Cmd+C on macOS.
  const copyKey = await page.evaluate(() => (/Mac|iPhone|iPad/.test(navigator.platform) ? 'Cmd+C' : 'Ctrl+C'));
  await expect(page.getByTestId('python-copy-status')).toHaveText(`Copy failed. Press ${copyKey} to copy the selected code.`);
  await expect(page.getByRole('button', { name: 'Copied' })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Copy' })).toBeVisible();
  const shown = await source(page).evaluate((element) => element.textContent ?? '');
  await expect.poll(async () => (await page.evaluate(() => window.getSelection()?.toString() ?? '')).trimEnd()).toBe(shown.trimEnd());
  await expect(source(page)).toBeFocused();
});
