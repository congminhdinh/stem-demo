import { expect, test, type Page } from '@playwright/test';
import { add, cmp, countUp, getVar, ifThen, join, num, print, program, repeat, setVar, text } from '../src/core/program/__fixtures__/ybc-blocks';
import { openApp, openProject } from './helpers';

// YB-5A (YB plan §13.7, §8.6): a Yolo:Bit-compatible project shows the MicroPython it generates,
// or why there is none; a generic project has no Python panel. Opened through the dev-only hook.

const ybcBoard = { id: 'ybc-board-1', deviceType: 'ybc-board', position: { x: 300, y: 200 } };
const project = (blocks: unknown, options: { profile?: string; components?: unknown[] } = {}) => ({
  schemaVersion: 1,
  id: 'ybc-python',
  name: 'Python',
  profile: options.profile ?? 'ybc-basic',
  circuit: { components: options.components ?? [ybcBoard], wires: [] },
  program: { blocks },
});

const source = (page: Page) => page.getByTestId('python-source');

test('shows the Python of the program, with only the claims that are true', async ({ page }) => {
  await openProject(page, project(program([setVar('x', num(1)), print(add(getVar('x'), num(2)))])));

  await expect(page.getByTestId('python-panel')).toBeVisible();
  await expect(source(page)).toHaveText(
    [
      '# Generated by STEM Studio for Yolo:Bit MicroPython (contract 1.0.0-draft.r3)',
      'import time',
      '',
      'x = 0',
      'y = 0',
      'z = 0',
      '',
      'x = 1',
      'print(x + 2)',
      '',
      'while True:',
      '    time.sleep_ms(10)',
      '',
    ].join('\n'),
  );
  await expect(page.getByTestId('python-claim')).toHaveText('MicroPython for the yolobit library of Yolo:Bit · not yet run on a physical board');
});

test('shows loops, count up with its bounds taken once, and text', async ({ page }) => {
  await openProject(
    page,
    project(
      program([
        setVar('y', num(3)),
        countUp('x', num(1), getVar('y'), 1, [print(join(text("it's "), getVar('x')))]),
        repeat(num(2), [ifThen(cmp('GT', getVar('y'), num(1)), [print(text('big'))])]),
      ]),
    ),
  );

  await expect(source(page)).toContainText(
    ['_cu_start_1 = 1', '_cu_end_1 = y', 'for x in range(_cu_start_1, _cu_end_1 + 1):', "    print('it\\'s ' + str(x))", 'for _r1 in range(2):'].join('\n'),
  );
});

test('follows a change of the project, and Advanced generates the same way', async ({ page }) => {
  await openProject(page, project(program([print(num(1))])));
  await expect(source(page)).toContainText('print(1)');

  await page.evaluate((next) => window.__stem?.loadProject(next), project(program([print(num(2))]), { profile: 'ybc-advanced' }));
  await expect(source(page)).toContainText('print(2)');
  await expect(source(page)).not.toContainText('print(1)');
});

test('downloads program.py with exactly the shown source, and copies it', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await openProject(page, project(program([print(text('héllo 😀'))])));
  await expect(source(page)).toContainText("print('héllo 😀')");
  const shown = await source(page).evaluate((element) => element.textContent ?? '');

  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download' }).click()]);
  expect(download.suggestedFilename()).toBe('program.py');
  const saved = await download.createReadStream().then(async (stream) => {
    const chunks: Buffer[] = [];
    for await (const chunk of stream) {
      chunks.push(chunk as Buffer);
    }
    return Buffer.concat(chunks).toString('utf8');
  });
  expect(saved).toBe(shown);

  await page.getByRole('button', { name: 'Copy' }).click();
  await expect(page.getByRole('button', { name: 'Copied' })).toBeVisible();
  // The Windows clipboard turns LF into CRLF; the text is otherwise the file.
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  expect(copied.split(String.fromCharCode(13, 10)).join(String.fromCharCode(10))).toBe(shown);
});

test('says why there is no Python, with the diagnostics Run gives, and offers no download', async ({ page }) => {
  await openProject(page, project(program([setVar('x', text('hi'))])));
  await expect(page.getByTestId('python-diagnostics')).toContainText('The program cannot run yet.');
  await expect(page.getByTestId('python-diagnostics')).toContainText('needs a whole number');
  await expect(page.getByRole('button', { name: 'Download' })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Copy' })).toBeDisabled();
  await expect(source(page)).toHaveCount(0);

  await page.getByRole('button', { name: 'Run' }).click();
  await expect(page.getByTestId('run-messages')).toContainText('needs a whole number');
});

test('says there is no Python for a circuit without a board, and for text the target file cannot hold', async ({ page }) => {
  await openProject(page, project(program([print(text('a'))]), { components: [] }));
  await expect(page.getByTestId('python-diagnostics')).toContainText('The circuit needs a board.');

  await page.evaluate((next) => window.__stem?.loadProject(next), project(program([print(text('lone \ud83d surrogate'))])));
  await expect(page.getByTestId('python-diagnostics')).toContainText('Python cannot be generated yet.');
  await expect(page.getByTestId('python-diagnostics')).toContainText('lone surrogate');
  // It still runs in the simulator: L-3 is not L-4.
  await page.getByRole('button', { name: 'Run' }).click();
  await expect(page.getByTestId('run-status')).toHaveText('Program finished — board powered');
});

