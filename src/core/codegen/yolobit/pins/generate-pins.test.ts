describe('API allowlist (plan §13.9, K2)', () => {
  const allowed = generatorAllowlist(contract);
  const pinForm = /^(pin[0-2]\.(write_digital|read_digital|read_analog))$/;
  const preambleAttributes = ['button_a.on_pressed', 'button_b.on_pressed', 'button_a.on_pressed_ab', 'button_b.on_pressed_ab'];

  /** Code only: no comments, no string literals. */
  const code = (source: string) => source.split('\n').map((line) => line.replace(/'(?:[^'\\]|\\.)*'/g, "''").replace(/#.*$/, '')).join('\n');

  it.each(pinCases)('$name imports, calls and reads only what the contract lists for the pins', ({ blocks }) => {
    const { source } = generate(blocks);
    const stripped = code(source);
    const imports = stripped.split('\n').filter((line) => /^(import|from)\s/.test(line));
    expect(imports).toEqual(['import time', 'from yolobit import *']);
    for (const line of imports) {
      expect(allowed.imports).toContain(line);
    }
    const preamble = stripped.split('\n').filter((line) => line.startsWith('button_'));
    expect(preamble).toEqual(yolobitModuleLines.slice(1));
    for (const line of preamble) {
      expect(allowed.preamble).toContain(line);
    }
    const attributes = [...stripped.matchAll(/\b([A-Za-z_]\w*)\.([A-Za-z_]\w*)/g)].map((match) => `${match[1]}.${match[2]}`);
    const unknown = attributes.filter((attribute) => attribute !== 'time.sleep_ms' && !pinForm.test(attribute) && !preambleAttributes.includes(attribute));
    expect(unknown).toEqual([]);
    const calls = [...stripped.matchAll(/\b([A-Za-z_]\w*)\s*\(/g)].map((match) => match[1] as string);
    const builtins = calls.filter((name) => ['print', 'range', 'str', 'int', 'len'].includes(name));
    for (const builtin of builtins) {
      expect(allowed.builtins).toContain(builtin);
    }
  });

  it('writes each pin call in exactly the form of its contract row', () => {
    const forms = { write: row('C-23').python?.form, read: row('C-24').python?.form, analog: row('C-25').python?.form };
    expect(forms).toEqual({
      write: 'pin<N>.write_digital(<value>)',
      read: '(pin<N>.read_digital() == 1)',
      analog: 'int(pin<N>.read_analog())',
    });
    const regex = (form: string) => new RegExp(form.replace(/[.()]/g, '\\$&').replace('<N>', '[0-2]').replace('<value>', '[01]'));
    const all = pinCases.map(({ blocks }) => generate(blocks).source).join('\n');
    expect(all).toMatch(regex(forms.write ?? ''));
    expect(all).toMatch(regex(forms.read ?? ''));
    expect(all).toMatch(regex(forms.analog ?? ''));
    // And nothing else of the module is spoken: no other pin call, no pull, no PWM, no servo, no pulse.
    expect(all).not.toMatch(/write_analog|servo_write|pulse_in|set_pull|pwm/i);
  });

  it('keeps the rows it generates exposable, and the rows it must not generate out', () => {
    for (const id of ['C-23', 'C-24', 'C-25']) {
      expect(exposureViolations(row(id), contract), id).toEqual([]);
    }
    // PWM and pulse are EXCLUDED (no Python at all in the contract); servo is an Advanced row of YB-7 that the
    // contract does describe, and this generator must not speak it yet.
    for (const id of ['C-26', 'C-28']) {
      expect(row(id).python, id).toBeUndefined();
    }
    for (const id of ['C-26', 'C-27', 'C-28']) {
      expect(generatedConstructs as readonly string[], id).not.toContain(id);
    }
    expect(generatedConstructs).toEqual(expect.arrayContaining(['C-23', 'C-24', 'C-25']));
  });
});

describe('what the generator refuses (K4: diagnostics, never half a program)', () => {
  const lit = (value: number, blockId = 'l'): Expr => ({ type: 'int', kind: 'int', value, blockId });
  const ir = (statement: YbcProgramIR['onStart'][number]): YbcProgramIR => ({ onStart: [statement], forever: null, variables: [] });
  const codes = (program: YbcProgramIR) => {
    const result = generateYbcMicroPython(program);
    return result.ok ? 'ok' : result.diagnostics.map((d) => `${d.code}@${d.blockId}`);
  };

  it('refuses a pin outside P0, P1 and P2, and a level that is not 0 or 1', () => {
    expect(codes(ir({ kind: 'call', op: 'digital.write', args: [lit(3), lit(1)], blockId: 'w' }))).toEqual(['value-out-of-range@w']);
    expect(codes(ir({ kind: 'call', op: 'digital.write', args: [lit(-1), lit(1)], blockId: 'w' }))).toEqual(['value-out-of-range@w']);
    expect(codes(ir({ kind: 'call', op: 'digital.write', args: [lit(0), lit(2)], blockId: 'w' }))).toEqual(['value-out-of-range@w']);
    const read = (pin: number): Expr => ({ type: 'int', kind: 'read', op: 'analogIn.read', args: [lit(pin)], blockId: 'r' });
    expect(codes(ir({ kind: 'print', value: read(5), blockId: 'p' }))).toEqual(['value-out-of-range@r']);
  });

  it('refuses a pin or a level the program only works out when it runs: the Python name is pinN', () => {
    const variable: Expr = { type: 'int', kind: 'variable', variable: 'x', blockId: 'v' };
    expect(codes(ir({ kind: 'call', op: 'digital.write', args: [variable, lit(1)], blockId: 'w' }))).toEqual(['unsupported-node@w']);
    expect(codes(ir({ kind: 'call', op: 'digital.write', args: [lit(0), variable], blockId: 'w' }))).toEqual(['unsupported-node@w']);
  });

  it('refuses the wrong number of arguments, and a read whose type is not the contract\'s', () => {
    expect(codes(ir({ kind: 'call', op: 'digital.write', args: [lit(0)], blockId: 'w' }))).toEqual(['unsupported-node@w']);
    expect(codes(ir({ kind: 'call', op: 'digital.write', args: [lit(0), lit(1), lit(1)], blockId: 'w' }))).toEqual(['unsupported-node@w']);
    const wrongType: Expr = { type: 'int', kind: 'read', op: 'digital.read', args: [lit(1)], blockId: 'r' };
    expect(codes(ir({ kind: 'print', value: wrongType, blockId: 'p' }))).toEqual(['type-mismatch@r']);
  });
});

