// The Python layer of the header pins (YB-4, plan R1: a construct has all four layers). Exact-source goldens in
// `pins/__golden__/`, the allowlist and the module lines tied to the contract, the domain refused at the
// generator, the syntax gate, and a parity check of what the generated text DOES against what the simulator's
// interpreter does with the same IR. None of it proves anything about a MicroPython or a Yolo:Bit (plan §6.9).

const contract = yolobitContract;
const row = (id: string) => {
  const found = contract.constructs.find((construct) => construct.id === id);
  if (!found) {
    throw new Error(`No contract row ${id}`);
  }
  return found;
};
const generate = (blocks: unknown) => {
  const generated = generateYbcMicroPython(compileBlocks(blocks));
  if (!generated.ok) {
    throw new Error(JSON.stringify(generated.diagnostics));
  }
  return generated;
};

