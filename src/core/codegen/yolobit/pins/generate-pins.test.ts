type Report = { status: 'pass' | 'fail' | 'pending'; checker: string | null; files: number; failures: { file: string; message: string }[] };
const check = (targets: string[]): Report => JSON.parse(spawnSync(process.execPath, ['scripts/check-python-syntax.mjs', '--json', ...targets], { encoding: 'utf8', timeout: 120_000 }).stdout) as Report;
const checkerAvailable = check([]).status !== 'pending';

describe.skipIf(!checkerAvailable)('syntax check of the generated pin programs', () => {
  it('passes on every pin golden (a syntax check proves syntax only, plan §6.9)', () => {
    const report = check([join(process.cwd(), 'src/core/codegen/yolobit/pins/__golden__')]);
    expect(report.failures).toEqual([]);
    expect(report.status).toBe('pass');
    expect(report.files).toBe(pinCases.length);
  });

  it('would notice a broken pin program (the gate is not vacuous)', () => {
    const dir = mkdtempSync(join(tmpdir(), 'bad-pin-py-'));
    try {
      writeFileSync(join(dir, 'bad.py'), 'from yolobit import *\nif (pin0.read_digital() == 1)\n    pin1.write_digital(1)\n');
      expect(check([dir]).status).toBe('fail');
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});

// --- parity: what the generated text does, against what the interpreter does -----------------------------

/** What the simulator's interpreter does with the IR on scripted hardware; ends at the first 10 ms pause. */
async function simulate(blocks: unknown, script: PinScript) {
  const calls: string[] = [];
  const counts = new Map<string, number>();
  const reading = (kind: 'digital' | 'analog', pin: string) => {
    const values = script[kind][pin] ?? [0];
    const key = `${kind}:${pin}`;
    const index = counts.get(key) ?? 0;
    counts.set(key, index + 1);
    return values[Math.min(index, values.length - 1)] as number;
  };
  const capabilities: Capabilities = {
    digital: {
      digitalWrite: (pin, level) => void calls.push(`write ${pin} ${level}`),
      digitalRead: (pin) => {
        calls.push(`read_digital ${pin}`);
        return reading('digital', pin) === 1 ? 1 : 0;
      },
    },
    analogIn: {
      analogRead: (pin) => {
        calls.push(`read_analog ${pin}`);
        return reading('analog', pin);
      },
    },
  };
  const runConsole = createRunConsole();
  let stop = () => {};
  const sleep: Sleep = (ms, signal) =>
    new Promise((_resolve, reject) => {
      signal.addEventListener('abort', () => reject(signal.reason), { once: true });
      if (ms === 10) {
        stop();
      }
    });
  const running = runYbc(compileBlocks(blocks), { sleep, console: runConsole }, capabilities);
  stop = running.stop;
  const outcome = await running.done;
  expect(['finished', 'stopped']).toContain(outcome.status);
  return { lines: runConsole.snapshot().lines, calls };
}

describe.skipIf(python === null)('the generated pin program does what the simulator does (CPython, fake yolobit)', () => {
  const runs = pinCases.flatMap(({ name, blocks, scripts }) => scripts.map((script, index) => ({ key: `${name}#${index}`, blocks, script })));
  const results = python
    ? runPinsUnderCpython(Object.fromEntries(runs.map(({ key, blocks, script }) => [key, { source: generate(blocks).source, script }])))
    : {};

  it('runs every case without a Python error', () => {
    expect(runs.map(({ key }) => results[key]?.error)).toEqual(runs.map(() => null));
  });

  it.each(runs.map((run) => [run.key, run] as const))('%s: the same pin calls in the same order, the same printed lines', async (key, { blocks, script }) => {
    const simulated = await simulate(blocks, script);
    expect(results[key]?.calls).toEqual(simulated.calls);
    expect(results[key]?.lines).toEqual(simulated.lines);
  });

  it('checks something: the calls are really made, and a short-circuit skips the read it should', async () => {
    expect(results['pins-digital-write#0']?.calls).toEqual(['write P0 1', 'write P1 0', 'write P2 1', 'write P0 0', 'write P0 1']);
    // P0 off: `and` does not read P1 (the right side), exactly as the interpreter does.
    const skipped = results['pins-expressions#1']?.calls ?? [];
    expect(skipped.slice(0, 5)).toEqual(['read_analog P0', 'read_analog P2', 'read_analog P1', 'read_digital P0', 'read_digital P0']);
    expect(skipped).not.toContain('read_digital P1');
    expect(await simulate(pinCases.find((c) => c.name === 'pins-expressions')?.blocks, (pinCases.find((c) => c.name === 'pins-expressions')?.scripts ?? [])[1] as PinScript)).toMatchObject({ calls: skipped });
  });
});

