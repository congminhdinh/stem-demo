describe('operators and precedence', () => {
  const [a, b, c, d] = ['a', 'b', 'c', 'd'].map(get) as [Expr, Expr, Expr, Expr];

  it.each([
    ['(a + b) * c', () => arith('*', arith('+', a, b), c), '(a + b) * c'],
    ['a + b * c', () => arith('+', a, arith('*', b, c)), 'a + b * c'],
    ['a - (b - c)', () => arith('-', a, arith('-', b, c)), 'a - (b - c)'],
    ['(a - b) - c', () => arith('-', arith('-', a, b), c), 'a - b - c'],
    ['a * (b * c)', () => arith('*', a, arith('*', b, c)), 'a * (b * c)'],
    ['a // (b + 1)', () => arith('//', a, arith('+', b, int(1))), 'a // (b + 1)'],
    ['a % (0 - b)', () => arith('%', a, arith('-', int(0), b)), 'a % (0 - b)'],
    ['(a // b) // c', () => arith('//', arith('//', a, b), c), 'a // b // c'],
    ['a // (b // c)', () => arith('//', a, arith('//', b, c)), 'a // (b // c)'],
    ['a % -3', () => arith('%', a, int(-3)), 'a % (-3)'],
    ['-3 // a', () => arith('//', int(-3), a), '(-3) // a'],
    ['a + b % c', () => arith('+', a, arith('%', b, c)), 'a + b % c'],
    ['(a % b) * c', () => arith('*', arith('%', a, b), c), 'a % b * c'],
  ])('%s', (_label, build, expected) => {
    expect(printed(build())).toBe(expected);
  });

  it.each([
    ['==', 'a == b'],
    ['!=', 'a != b'],
    ['<', 'a < b'],
    ['<=', 'a <= b'],
    ['>', 'a > b'],
    ['>=', 'a >= b'],
  ] as const)('writes the comparison %s', (op, expected) => {
    expect(printed(compare(op, a, b))).toBe(expected);
  });

  it('keeps arithmetic inside comparisons without needless parentheses, and never chains a comparison', () => {
    expect(printed(compare('<', arith('+', a, b), arith('*', c, d)))).toBe('a + b < c * d');
    expect(printed(compare('==', compare('<', a, b), compare('>', c, d)))).toBe('(a < b) == (c > d)');
    expect(printed(compare('==', compare('<', a, b), bool(true)))).toBe('(a < b) == True');
  });

  it.each([
    ['(a < b) and (c != d)', () => and(compare('<', a, b), compare('!=', c, d)), '(a < b) and (c != d)'],
    ['not (a == b)', () => not(compare('==', a, b)), 'not (a == b)'],
    ['not not True', () => not(not(bool(true))), 'not not True'],
    ['(p or q) and r', () => and(or(bool(true), bool(false)), bool(true)), '(True or False) and True'],
    ['p or (q and r)', () => or(bool(true), and(bool(false), bool(true))), 'True or (False and True)'],
    ['p and (q and r) keeps the grouping', () => and(bool(true), and(bool(true), bool(false))), 'True and (True and False)'],
    ['not (p and q)', () => not(and(bool(true), bool(false))), 'not (True and False)'],
  ])('%s', (_label, build, expected) => {
    expect(printed(build())).toBe(expected);
  });

  it('writes and / or / not, never && || !', () => {
    expect(printed(and(or(bool(true), bool(false)), not(bool(true))))).not.toMatch(/&&|\|\||!(?!=)/);
  });

  it('never writes / or **', () => {
    const text = source(program([print(arith('//', a, b)), print(arith('%', a, b)), print(arith('*', a, b))]));
    expect(text).not.toMatch(/[^/]\/[^/]|\*\*/);
  });

  it('writes 100 levels of nesting', () => {
    let deep: Expr = int(1);
    for (let level = 0; level < 99; level += 1) {
      deep = arith('+', int(1), deep);
    }
    expect(printed(deep)?.match(/\(/g)).toHaveLength(98);
  });
});

describe('text', () => {
  it.each([
    ['plain', "'plain'"],
    ["it's", "'it\\'s'"],
    ['say "hi"', `'say "hi"'`],
    ['back\\slash', "'back\\\\slash'"],
    ['line\nbreak', "'line\\nbreak'"],
    ['cr\rtab\t', "'cr\\rtab\\t'"],
    ['\u0000\u001f\u007f\u0085\u009f', "'\\x00\\x1f\\x7f\\x85\\x9f'"],
    ['Xin chào, thế giới', "'Xin chào, thế giới'"],
    ['😀', "'😀'"],
    ['', "''"],
    ["\\'", "'\\\\\\''"],
    ['  ﻿', "'  ﻿'"],
  ])('writes %j as %s', (text, expected) => {
    expect(pythonString(text)).toBe(expected);
  });

  it('has no UTF-8 form for a lone surrogate', () => {
    expect(pythonString('a\ud800b')).toBeNull();
    expect(pythonString('\udc00')).toBeNull();
    expect(pythonString('😀')).not.toBeNull();
  });

  it('refuses a lone surrogate with a diagnostic on its block, and writes nothing', () => {
    const bad = str('a\ud83dz');
    const result = failure(program([print(bad)]));
    expect(result).toEqual({ ok: false, diagnostics: [{ severity: 'error', code: 'invalid-literal', message: expect.any(String), blockId: bad.blockId }] });
    expect('source' in result).toBe(false);
  });

  it('accepts 1000 characters and refuses 1001', () => {
    expect(generateYbcMicroPython(program([print(str('x'.repeat(1000)))])).ok).toBe(true);
    expect(failure(program([print(str('x'.repeat(1001)))])).diagnostics).toMatchObject([{ code: 'limit-exceeded' }]);
  });

  it('joins through str(), left to right, each part once', () => {
    expect(printed(join(str('a'), get('x'), bool(true), arith('+', get('x'), int(1))))).toBe("'a' + str(x) + str(True) + str(x + 1)");
    expect(printed(join(str('a'), join(str('b'), str('c'))))).toBe("'a' + ('b' + 'c')");
    expect(printed(join(join(str('a'), str('b')), str('c')))).toBe("'a' + 'b' + 'c'");
    expect(printed(join(get('x'), get('y')))).toBe('str(x) + str(y)');
    expect(printed(join(str('only')))).toBe("'only'");
    expect(printed(join())).toBe("''");
    expect(printed(compare('==', join(str('a'), get('x')), str('a1')))).toBe("'a' + str(x) == 'a1'");
  });
});

describe('statements', () => {
  it('writes an empty suite as pass, for every construct that has one', () => {
    const text = source(
      program([
        { kind: 'if', branches: [{ condition: bool(true), body: [] }], else: [], blockId: id() },
        { kind: 'while', condition: bool(false), body: [], blockId: id() },
        repeat(int(1), [{ kind: 'noop', blockId: id() }]),
      ]),
    );
    expect(text).toContain('if True:\n    pass\nwhile False:\n    pass\nfor _r1 in range(1):\n    pass\n');
  });

  it('writes if / elif / else in order, and no else for an empty else', () => {
    const text = source(
      program([
        {
          kind: 'if',
          branches: [
            { condition: compare('<', get('x'), int(1)), body: [print(int(1))] },
            { condition: compare('<', get('x'), int(2)), body: [print(int(2))] },
          ],
          else: [print(int(3))],
          blockId: id(),
        },
      ]),
    );
    expect(text).toContain('if x < 1:\n    print(1)\nelif x < 2:\n    print(2)\nelse:\n    print(3)\n');
  });

  it('numbers the repeat counters and the count-up bounds in the order of the nodes, outer first (a count up with literal bounds keeps its number)', () => {
    const text = source(
      program([
        repeat(int(2), [countUp('x', get('a'), get('b'), [countUp('x', int(1), int(2), [repeat(int(1))], 2)])]),
        countUp('x', get('c'), int(5), [], 3),
      ]),
    );
    expect(text).toContain(
      [
        'for _r1 in range(2):',
        '    _cu_start_1 = a',
        '    _cu_end_1 = b',
        '    for x in range(_cu_start_1, _cu_end_1 + 1):',
        '        for x in range(1, 3, 2):',
        '            for _r2 in range(1):',
        '                pass',
        '_cu_start_3 = c',
        '_cu_end_3 = 5',
        'for x in range(_cu_start_3, _cu_end_3 + 1, 3):',
        '    pass',
        '',
      ].join('\n'),
    );
  });

  it('takes the start before the end, each once, in separate statements, even for a literal start', () => {
    const text = source(program([countUp('x', int(1), get('b'), [print(get('x'))])]));
    expect(text).toContain('_cu_start_1 = 1\n_cu_end_1 = b\nfor x in range(_cu_start_1, _cu_end_1 + 1):\n');
    // `b` is read once: after the declarations, only the end bound mentions it.
    expect(text.slice(text.indexOf('_cu_start_1')).match(/\bb\b/g)).toHaveLength(1);
  });

  it('folds literal bounds and writes the step only when it is not 1', () => {
    const run = (step: number) => source(program([countUp('x', int(0), int(1_000_000), [], step)]));
    expect(run(1)).toContain('for x in range(0, 1000001):');
    expect(run(7)).toContain('for x in range(0, 1000001, 7):');
  });

  it('writes the wait as milliseconds, without conversion', () => {
    expect(source(program([{ kind: 'waitMs', ms: int(250), blockId: id() }, { kind: 'waitMs', ms: get('x'), blockId: id() }]))).toContain(
      'time.sleep_ms(250)\ntime.sleep_ms(x)\n',
    );
  });
});

describe('names', () => {
  it.each([
    ['x', 'x'],
    ['my value', 'my_value'],
    ['hello-world', 'hello_world'],
    ['a.b', 'a_b'],
    ['1name', 'v_1name'],
    ['tên', 'ten'],
    ['Đức Độ', 'Duc_Do'],
    ['_private', 'v_private'],
    ['__', 'v_'],
    ['', 'v_'],
    ['😀', 'v_'],
    ['日本', 'v_'],
  ])('sanitizes %j to %s', (name, expected) => {
    expect(sanitizeName(name)).toBe(expected);
  });

  const namesOf = (list: string[]) => {
    const assigned = assignNames(list.map((name, index) => ({ id: `id${index}`, name })));
    if (!assigned.ok) {
      throw new Error(assigned.message);
    }
    return [...assigned.names.values()];
  };

  it('keeps every name away from keywords, builtins and the target', () => {
    expect(namesOf(['class', 'for', 'True', 'None', 'print', 'range', 'str', 'int', 'len', 'time', 'music', 'random', 'display', 'button_a', 'pin3', 'Image'])).toEqual([
      'class_2', 'for_2', 'True_2', 'None_2', 'print_2', 'range_2', 'str_2', 'int_2', 'len_2', 'time_2', 'music_2', 'random_2', 'display_2', 'button_a_2', 'pin3_2', 'Image_2',
    ]);
  });

  it('makes names unique in a stable order, skipping a suffix that is taken', () => {
    expect(namesOf(['duplicate', 'duplicate', 'duplicate'])).toEqual(['duplicate', 'duplicate_2', 'duplicate_3']);
    expect(namesOf(['a', 'a', 'a_2'])).toEqual(['a', 'a_2', 'a_2_2']);
    expect(namesOf(['a_2', 'a', 'a'])).toEqual(['a_2', 'a', 'a_3']);
    expect(namesOf(['a b', 'a-b', 'a.b'])).toEqual(['a_b', 'a_b_2', 'a_b_3']);
    expect(namesOf(['_x', 'v_x'])).toEqual(['v_x', 'v_x_2']);
  });

  it('refuses a variable id that is declared twice', () => {
    expect(assignNames([{ id: 'v', name: 'a' }, { id: 'v', name: 'b' }]).ok).toBe(false);
    expect(failure(program([], null, [{ id: 'v', name: 'a', type: 'int' }, { id: 'v', name: 'b', type: 'int' }])).diagnostics).toMatchObject([{ code: 'invalid-identifier' }]);
  });

  it('gives two variables with one name and different ids two names, and keeps them apart', () => {
    const text = source(
      program([set('p', int(1)), set('q', int(2)), print(arith('+', get('p'), get('q')))], null, [
        { id: 'p', name: 'score', type: 'int' },
        { id: 'q', name: 'score', type: 'int' },
      ]),
    );
    expect(text).toContain('score = 0\nscore_2 = 0\n');
    expect(text).toContain('score = 1\nscore_2 = 2\nprint(score + score_2)\n');
  });

  it('never gives a learner variable a name that starts with an underscore, so the generator names cannot collide', () => {
    const result = generateYbcMicroPython(program([], null, [{ id: 'a', name: '_r1', type: 'int' }, { id: 'b', name: '_cu_start_1', type: 'int' }])) as Extract<GenerateResult, { ok: true }>;
    expect(Object.values(result.names)).toEqual(['v_r1', 'v_cu_start_1']);
  });

  it('reports the names by variable id and never writes the id', () => {
    const result = generateYbcMicroPython(program([], null, [{ id: 'Zq$1', name: 'my value', type: 'int' }])) as Extract<GenerateResult, { ok: true }>;
    expect(result.names).toEqual({ 'Zq$1': 'my_value' });
    expect(result.source).not.toContain('Zq$1');
  });
});

describe('diagnostics', () => {
  it('refuses a node the generator does not know, with the block id, and writes nothing', () => {
    const unknown = { kind: 'weird', blockId: 'w', type: 'int' } as unknown as Expr;
    expect(failure(program([print(unknown)]))).toEqual({
      ok: false,
      diagnostics: [{ severity: 'error', code: 'unsupported-node', message: expect.any(String), blockId: 'w' }],
    });
  });

  it.each(['random', 'event', 'pwm', 'elapsed', 'display', 'button', 'pin', 'servo', 'music', 'function'])(
    'refuses the %s node: excluded, deferred or a later phase',
    (kind) => {
      const statement = { kind, blockId: `s-${kind}` } as unknown as YbcStatement;
      expect(failure(program([statement])).diagnostics).toEqual([
        { severity: 'error', code: 'unsupported-node', message: expect.any(String), blockId: `s-${kind}` },
      ]);
    },
  );

  it('refuses types that do not fit, with the block id', () => {
    const wrongValue = str('no');
    expect(failure(program([set('x', wrongValue)])).diagnostics).toMatchObject([{ code: 'type-mismatch', blockId: wrongValue.blockId }]);
    expect(failure(program([{ kind: 'while', condition: int(1), body: [], blockId: id() }])).diagnostics).toMatchObject([{ code: 'type-mismatch' }]);
    expect(failure(program([print(arith('+', int(1), bool(true)))])).diagnostics).toMatchObject([{ code: 'type-mismatch' }]);
    expect(failure(program([print(compare('<', str('a'), str('b')))])).diagnostics[0]).toMatchObject({ code: 'type-mismatch' });
    expect(failure(program([print(compare('==', int(1), str('a')))])).diagnostics).toMatchObject([{ code: 'type-mismatch' }]);
    expect(failure(program([print(and(int(1), bool(true)))])).diagnostics[0]).toMatchObject({ code: 'type-mismatch' });
    expect(failure(program([print(not(int(1)))])).diagnostics).toMatchObject([{ code: 'type-mismatch' }]);
    expect(failure(program([], null, [{ id: 's', name: 's', type: 'str' as 'int' }])).diagnostics).toMatchObject([{ code: 'type-mismatch' }]);
  });

  it('refuses a variable that is not declared', () => {
    expect(failure(program([print(get('nope'))])).diagnostics).toMatchObject([{ code: 'unknown-variable' }]);
    expect(failure(program([set('nope', int(1))])).diagnostics).toMatchObject([{ code: 'unknown-variable' }]);
    expect(failure(program([countUp('nope', int(0), int(1))])).diagnostics).toMatchObject([{ code: 'unknown-variable' }]);
  });

  it('refuses literals outside the domain of the contract, and does not clamp or round them', () => {
    const codes = (statement: YbcStatement) => failure(program([statement])).diagnostics.map((diagnostic) => diagnostic.code);
    const wait = (ms: number): YbcStatement => ({ kind: 'waitMs', ms: int(ms), blockId: id() });
    expect(codes(wait(-1))).toEqual(['value-out-of-range']);
    expect(codes(wait(60001))).toEqual(['value-out-of-range']);
    expect(generateYbcMicroPython(program([wait(60000)])).ok).toBe(true);
    expect(codes(repeat(int(1_000_001)))).toEqual(['value-out-of-range']);
    expect(codes(repeat(int(-1_000_001)))).toEqual(['value-out-of-range']);
    expect(generateYbcMicroPython(program([repeat(int(-1_000_000))])).ok).toBe(true);
    expect(codes(countUp('x', int(-1), int(5)))).toEqual(['value-out-of-range']);
    expect(codes(countUp('x', int(0), int(1_000_001)))).toEqual(['value-out-of-range']);
    expect(codes(countUp('x', int(0), int(5), [], 0))).toEqual(['value-out-of-range']);
    expect(codes(countUp('x', int(0), int(5), [], 1_000_001))).toEqual(['value-out-of-range']);
    expect(codes(countUp('x', int(0), int(5), [], 1.5))).toEqual(['value-out-of-range']);
    expect(codes(countUp('x', int(5), int(1)))).toEqual(['descending-range-not-supported']);
    expect(generateYbcMicroPython(program([countUp('x', int(1_000_000), int(1_000_000), [], 1_000_000)])).ok).toBe(true);
  });

  it('refuses nesting beyond its limits instead of overflowing the stack', () => {
    let statement: YbcStatement = print(int(1));
    for (let level = 0; level < 70; level += 1) {
      statement = { kind: 'while', condition: bool(true), body: [statement], blockId: id() };
    }
    expect(failure(program([statement])).diagnostics[0]).toMatchObject({ code: 'limit-exceeded' });
    let expr: Expr = int(1);
    for (let level = 0; level < 5000; level += 1) {
      expr = arith('+', int(1), expr);
    }
    expect(failure(program([print(expr)])).diagnostics.map((diagnostic) => diagnostic.code)).toContain('limit-exceeded');
  });

  it('collects every problem, each with its own block', () => {
    const first = get('nope');
    const second = int(1.5);
    expect(failure(program([print(first), print(second)])).diagnostics.map((diagnostic) => diagnostic.blockId)).toEqual([first.blockId, second.blockId]);
  });
});

