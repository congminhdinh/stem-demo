import { describe, expect, it } from 'vitest';
import type { Expr, YbcProgramIR, YbcStatement } from '../../program/ybc-ir';
import { generateYbcMicroPython, pythonString, type GenerateResult } from './generate';
import { assignNames, sanitizeName } from './names';

// Unit tests of the generator on hand-made IR: literals, precedence, names, text, diagnostics.

let counter = 0;
const id = () => `b${++counter}`;
const int = (value: number): Expr => ({ type: 'int', kind: 'int', value, blockId: id() });
const bool = (value: boolean): Expr => ({ type: 'bool', kind: 'bool', value, blockId: id() });
const str = (value: string): Expr => ({ type: 'str', kind: 'str', value, blockId: id() });
const get = (variable: string): Expr => ({ type: 'int', kind: 'variable', variable, blockId: id() });
const arith = (op: '+' | '-' | '*' | '//' | '%', left: Expr, right: Expr): Expr => ({ type: 'int', kind: 'arith', op, left, right, blockId: id() });
const compare = (op: '==' | '!=' | '<' | '<=' | '>' | '>=', left: Expr, right: Expr): Expr => ({ type: 'bool', kind: 'compare', op, left, right, blockId: id() });
const and = (left: Expr, right: Expr): Expr => ({ type: 'bool', kind: 'logic', op: 'and', left, right, blockId: id() });
const or = (left: Expr, right: Expr): Expr => ({ type: 'bool', kind: 'logic', op: 'or', left, right, blockId: id() });
const not = (value: Expr): Expr => ({ type: 'bool', kind: 'not', value, blockId: id() });
const join = (...parts: Expr[]): Expr => ({ type: 'str', kind: 'join', parts, blockId: id() });
const print = (value: Expr): YbcStatement => ({ kind: 'print', value, blockId: id() });
const set = (variable: string, value: Expr): YbcStatement => ({ kind: 'set', variable, value, blockId: id() });
const countUp = (variable: string, from: Expr, to: Expr, body: YbcStatement[] = [], step = 1): YbcStatement => ({
  kind: 'countUp', variable, from, to, step, body, blockId: id(),
});
const repeat = (times: Expr, body: YbcStatement[] = []): YbcStatement => ({ kind: 'repeat', times, body, blockId: id() });

const variables = (...names: string[]) => names.map((name) => ({ id: name, name, type: 'int' as const }));
const program = (onStart: YbcStatement[], forever: YbcStatement[] | null = null, vars = variables('a', 'b', 'c', 'd', 'x', 'y')): YbcProgramIR => ({
  onStart,
  forever,
  variables: vars,
});

function source(ir: YbcProgramIR): string {
  const result = generateYbcMicroPython(ir);
  if (!result.ok) {
    throw new Error(JSON.stringify(result.diagnostics));
  }
  return result.source;
}
const failure = (ir: YbcProgramIR) => {
  const result = generateYbcMicroPython(ir);
  if (result.ok) {
    throw new Error(`expected diagnostics, got:\n${result.source}`);
  }
  return result;
};
/** The one `print(...)` argument of a program that prints one expression. */
const printed = (expr: Expr) => {
  const line = source(program([print(expr)])).split('\n').find((candidate) => candidate.startsWith('print('));
  return line?.slice('print('.length, -1);
};

describe('the file', () => {
  it('is the comment, the import, the variables, on start, then the idle loop; LF, newline at the end, no trailing spaces', () => {
    const text = source(program([print(int(1))], null, variables('x')));
    expect(text).toBe(
      ['# Generated by STEM Studio for Yolo:Bit MicroPython (contract 1.0.0-draft.r3)', 'import time', '', 'x = 0', '', 'print(1)', '', 'while True:', '    time.sleep_ms(10)', ''].join('\n'),
    );
    expect(text).not.toMatch(/[ \t]$/m);
    expect(text).not.toContain('\r');
  });

  it('puts the forever body before the 10 ms pause, and needs no variables or on start', () => {
    expect(source(program([], [print(int(1))], []))).toBe(
      ['# Generated by STEM Studio for Yolo:Bit MicroPython (contract 1.0.0-draft.r3)', 'import time', '', 'while True:', '    print(1)', '    time.sleep_ms(10)', ''].join('\n'),
    );
  });

  it('imports only time: no random, no yolobit, no music, nothing the program does not use', () => {
    const text = source(program([print(int(1))]));
    expect(text.match(/^(import|from) .*/gm)).toEqual(['import time']);
    expect(text).not.toMatch(/random|yolobit|music|display|button|pin\d|event|PWM/i);
  });

  it('keeps the board alive after on start when there is no forever (plan §13.3 item 8, contract IM-6, E6)', () => {
    // The simulator FINISHES the on-start body (status `finished`) but the board stays powered until Stop (E6);
    // the program has no end on the board (C-41 is avoided), so the file ends in the idle loop, exactly as with a forever.
    const idle = ['while True:', '    time.sleep_ms(10)', ''].join(String.fromCharCode(10));
    expect(source(program([print(int(1))], null)).endsWith(idle)).toBe(true);
    expect(source(program([print(int(1))], null))).toBe(source(program([print(int(1))], [])));
  });

  it('follows the import policy of contract IM-1 to IM-3: `import time` always, yolobit and music only for their constructs', () => {
    // IM-2 / IM-3 / plan §13.3 item 2: "import only what is used". No YB-5A construct belongs to `yolobit` or `music`.
    for (const ir of [program([]), program([print(int(1))], [print(str('x'))]), program([{ kind: 'waitMs', ms: int(5), blockId: id() }])]) {
      const text = source(ir);
      expect(text.match(/^(import|from) .*/gm)).toEqual(['import time']);
      expect(text).not.toMatch(/from yolobit|import music|on_pressed|import random/);
    }
  });

  it('is the same bytes every time, whatever the order of the keys of the IR', () => {
    const ir = program([set('x', arith('+', int(1), int(2))), repeat(int(2), [print(get('x'))])]);
    const reversed = JSON.parse(JSON.stringify(ir), (_key, value: unknown) =>
      value && typeof value === 'object' && !Array.isArray(value) ? Object.fromEntries(Object.entries(value).reverse()) : value,
    ) as YbcProgramIR;
    expect(source(reversed)).toBe(source(ir));
    expect(source(ir)).toBe(source(ir));
  });

  it('maps lines to the blocks that produced them', () => {
    const first = set('x', int(1));
    const second = print(get('x'));
    const result = generateYbcMicroPython(program([first, second], null, variables('x'))) as Extract<GenerateResult, { ok: true }>;
    const lines = result.source.split('\n');
    for (const { line, blockId } of result.lineMap) {
      expect(lines[line - 1]).toBe(blockId === first.blockId ? 'x = 1' : 'print(x)');
    }
    expect(result.lineMap.map((entry) => entry.blockId)).toEqual([first.blockId, second.blockId]);
  });
});

