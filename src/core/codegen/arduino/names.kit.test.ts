import { describe, expect, it } from 'vitest';
import { drivers, productionKits, unoR3Board, type Kit } from '../../hardware';
import type { YbcProgramIR, YbcStatement } from '../../program/ybc-ir';
import { generateUnoSketch } from './generate';
import { assignCppNames, isReservedCppName, isReservedCppNameFor } from './names';

// N19 A4 (ruling A23 names): a sketch keeps away only from the names of its own kit: the roles the kit has, the pin macros its drivers
// can define, and what the drivers' C++ and libraries define at file scope. So a rover program means the same C++ as before the gripper
// car's kit existed, and a gripper program cannot take `gripperSet`, `colorIs`, `Wire` or a twi_* function of the Wire library.

const rover = productionKits.get({ id: 'ref-uno-rover', version: '0' }) as Kit;
const gripper = productionKits.get({ id: 'ref-uno-gripper', version: '0' }) as Kit;

const namesFor = (kit: Kit, ...list: string[]) => {
  const assigned = assignCppNames(
    list.map((name, index) => ({ id: `v${String(index)}`, name })),
    kit,
  );
  if (!assigned.ok) {
    throw new Error(assigned.message);
  }
  return [...assigned.names.values()];
};

/** The names of the probe: the gripper car's roles, helpers, pin macros and Wire's, and rover names that stay taken. */
const probe = [
  'gripper', 'irClaw', 'color1', 'gripperClaw', 'gripperLift', 'gripperSet', 'colorWrite', 'colorBegin', 'colorFetch', 'colorClassify', 'colorIs',
  'colorRaw', 'colorRgbc', 'colorC', 'colorR', 'colorG', 'colorB', 'COLOR_ADDR', 'COLOR_RULES', 'COLOR_RULE_COUNT', 'Wire', 'TwoWire', 'TwoWire_h',
  'BUFFER_LENGTH', 'WIRE_HAS_END', 'twi_init', 'twi_readFrom', 'GRIPPER_CLAW', 'GRIPPER_LIFT', 'IR_CLAW_PIN', 'COLOR1_SDA', 'COLOR1_SCL',
  'MOTOR_LEFT_CLAW', 'SERVO1_SDA', 'LED1_LIFT', 'servo1', 'buzzer', 'MOTOR_LEFT_EN', 'LED1_EN', 'BUZZER_TRIG',
];

/**
 * The sketch master 675cff6 (before A2+A3 added the gripper car's kit) writes for the probe on ref-uno-rover@0: every name as it is,
 * but servo1, buzzer and three pin macros of the rover's roles (generated there with this very IR; the report says how).
 */
const masterRoverSketch = [
  '// Scenario: none, kit: ref-uno-rover@0, board: uno-r3@0',
  '// Generated by STEM Studio from the blocks: editing this code does not change the lab.',
  '// Target: arduino:avr:uno, contract uno-arduino-avr 0.1.7. Libraries: arduino:avr@1.8.8 (LGPL-2.1)',
  '',
  ...probe.map((name) => `long ${['servo1', 'buzzer', 'MOTOR_LEFT_EN', 'LED1_EN', 'BUZZER_TRIG'].includes(name) ? `${name}_2` : name} = 0L;`),
  '',
  'void setup() {',
  ...probe.map((name, index) => `  ${['servo1', 'buzzer', 'MOTOR_LEFT_EN', 'LED1_EN', 'BUZZER_TRIG'].includes(name) ? `${name}_2` : name} = ${String(index)}L;`),
  '}',
  '',
  'void loop() {',
  '}',
  '',
].join('\n');

const set = (id: string, value: number): YbcStatement => ({ kind: 'set', variable: id, value: { blockId: `n-${id}`, type: 'int', kind: 'int', value }, blockId: `set-${id}` });
const probeIr: YbcProgramIR = {
  onStart: probe.map((_, index) => set(`v${String(index)}`, index)),
  forever: null,
  variables: probe.map((name, index) => ({ id: `v${String(index)}`, name, type: 'int' })),
  numeric: 'cxx-int32',
  loopPauseUs: 0,
};

/** The names a driver's C++ declares at file scope (its globals, its helper's functions, variables, tables and macros). */
function declaredNames(text: string): string[] {
  return text.split('\n').flatMap((line) => {
    const define = /^#define (\w+)/.exec(line);
    if (define) {
      return [define[1] ?? ''];
    }
    if (/^[\s}#]/.test(line) || line === '') {
      return [];
    }
    const declared = /(\w+)\s*[([=;]/.exec(line);
    return declared ? [declared[1] ?? ''] : [];
  });
}

describe('the names a sketch keeps away from are its kit’s (N19 A4, ruling A23)', () => {
  it('a rover program naming a variable gripper gives master’s C++', () => {
    const generated = generateUnoSketch(probeIr, { kit: rover, board: unoR3Board });
    expect(generated.ok && generated.source).toBe(masterRoverSketch);
  });

  it('keeps a rover sketch’s reserved roles and pin macros as they were: every role of the rover, its drivers’ pin names', () => {
    expect(namesFor(rover, 'motorLeft', 'servo1', 'buzzer', 'button1', 'ULTRASONIC_ECHO', 'BUTTON1_EN', 'LINE_LEFT_TRIG', 'motorSet', 'servoSet', 'buzzerTone', 'ultrasonicCm')).toEqual([
      'motorLeft_2', 'servo1_2', 'buzzer_2', 'button1_2', 'ULTRASONIC_ECHO_2', 'BUTTON1_EN_2', 'LINE_LEFT_TRIG_2', 'motorSet_2', 'servoSet_2', 'buzzerTone_2', 'ultrasonicCm_2',
    ]);
  });

  it('moves every name of the gripper car’s modules in a gripper sketch, and frees the roles that kit lacks', () => {
    expect(namesFor(gripper, ...probe)).toEqual(
      probe.map((name) => (['colorRgbc', 'SERVO1_SDA', 'servo1', 'buzzer', 'BUZZER_TRIG'].includes(name) ? name : `${name}_2`)),
    );
    // A role of the kit with a pin name of its drivers is a macro the kit could define (LED1_LIFT, MOTOR_LEFT_CLAW); a role it lacks
    // never is (BUZZER_TRIG, SERVO1_SDA). colorRgbc is no name of the colour driver's C++ (its reading is colorC, colorR, colorG, colorB).
    expect(namesFor(gripper, 'LED1_CLAW', 'MOTOR_RIGHT_SDA', 'IR_CLAW_EN', 'BUZZER_PIN', 'SERVO1_PIN')).toEqual(['LED1_CLAW_2', 'MOTOR_RIGHT_SDA_2', 'IR_CLAW_EN_2', 'BUZZER_PIN', 'SERVO1_PIN']);
  });

  it('takes every file-scope name the gripper car’s drivers declare, and every twi_* function the Wire library links', () => {
    for (const port of gripper.ports) {
      const module = gripper.modules.find((candidate) => candidate.port === port.id);
      for (const op of Object.values(drivers[port.driver].ops)) {
        const text = [...op.cpp.globals(port, module?.role ?? ''), op.cpp.helper?.text ?? '', ...drivers[port.driver].defines(port, module?.role ?? '')].join('\n');
        for (const name of declaredNames(text)) {
          expect(isReservedCppNameFor(gripper, name), `${port.driver} ${name}`).toBe(true);
        }
      }
    }
    // Wire 1.0 of arduino:avr 1.8.8: Wire.h's macros, its class and object, and twi.c's global functions (avr-gcc-nm of the build; a
    // learner global of each name fails to compile or link, the report gives the run).
    const wire = ['TwoWire_h', 'BUFFER_LENGTH', 'WIRE_HAS_END', 'TwoWire', 'Wire', 'twi_attachSlaveRxEvent', 'twi_attachSlaveTxEvent', 'twi_disable', 'twi_handleTimeout', 'twi_init',
      'twi_manageTimeoutFlag', 'twi_readFrom', 'twi_releaseBus', 'twi_reply', 'twi_setAddress', 'twi_setFrequency', 'twi_setTimeoutInMicros', 'twi_stop', 'twi_transmit', 'twi_writeTo'];
    expect(wire.filter((name) => !isReservedCppNameFor(gripper, name))).toEqual([]);
    expect(wire.filter((name) => isReservedCppNameFor(rover, name))).toEqual([]);
    // What twi.c keeps to itself (static) or twi.h defines (not included by Wire.h) does not clash: free.
    expect(['twi_state', 'TWI_FREQ', 'TWI_BUFFER_LENGTH', 'WIRE_HAS_TIMEOUT'].filter((name) => isReservedCppNameFor(gripper, name))).toEqual([]);
  });

  it('keeps every kit’s names out without a kit (any sketch)', () => {
    for (const name of ['gripper', 'irClaw', 'color1', 'servo1', 'buzzer', 'gripperSet', 'colorIs', 'Wire', 'twi_init', 'GRIPPER_CLAW', 'MOTOR_LEFT_CLAW', 'COLOR1_SDA']) {
      expect(isReservedCppName(name), name).toBe(true);
    }
  });
});
