describe('two or more reads of the robot in one unsequenced expression (contract §3.5, 0.1.3)', () => {
  const lineRaw = (role: 'lineLeft' | 'lineCenter' | 'lineRight'): Expr => ({ blockId: id(), type: 'int', kind: 'read', op: 'line.raw', operand: { kind: 'role', role } });
  const dark = (role: 'lineLeft' | 'lineCenter' | 'lineRight'): Expr => ({ blockId: id(), type: 'bool', kind: 'read', op: 'line.dark', operand: { kind: 'role', role } });
  const millis = (): Expr => ({ blockId: id(), type: 'int', kind: 'read', op: 'time.millis' });
  const x = (): Expr => ({ blockId: id(), type: 'int', kind: 'variable', variable: 'x' });
  const arith = (op: '+' | '-', left: Expr, right: Expr): Expr => ({ blockId: id(), type: 'int', kind: 'arith', op, left, right });
  const compare = (op: '<' | '>' | '==', left: Expr, right: Expr): Expr => ({ blockId: id(), type: 'bool', kind: 'compare', op, left, right });
  const logic = (op: 'and' | 'or', left: Expr, right: Expr): Expr => ({ blockId: id(), type: 'bool', kind: 'logic', op, left, right });
  const setupOf = (ir: YbcProgramIR) => bodyOf(ok(generateUnoSketch(ir, { kit, board })).source, 'setup');
  const L = 'LINE_LEFT_PIN';
  const R = 'LINE_RIGHT_PIN';

  it('assigns each read to a temporary with the comma operator, left to right, and declares the temporaries after the setup lines', () => {
    expect(setupOf(uno([printIt(arith('-', lineRaw('lineLeft'), lineRaw('lineRight')))]))).toEqual([
      '  Serial.begin(9600);',
      '  long _s1;',
      '  long _s2;',
      `  Serial.println((_s1 = (long)analogRead(${L}), _s2 = (long)analogRead(${R}), sub32(_s1, _s2)));`,
    ]);
  });

  it('takes the reads in the simulator’s depth-first order, the rest of the expression on the temporaries', () => {
    const expr = compare('>', lineRaw('lineLeft'), arith('-', x(), millis()));
    expect(setupOf(uno([printIt(expr)])).at(-1)).toBe(
      `  Serial.println((_s1 = (long)analogRead(${L}), _s2 = (long)millis(), (_s1 > sub32(x, _s2))));`,
    );
  });

  it('wraps a call whose two value arguments read the robot (buzzerTone), and sequences inside the one argument of any other call', () => {
    const tone: YbcStatement = { kind: 'call', op: 'buzzer.tone', operand: { kind: 'role', role: 'buzzer' }, args: [arith('-', x(), millis()), lineRaw('lineLeft')], blockId: id() };
    const motor: YbcStatement = { kind: 'call', op: 'motor.set', operand: { kind: 'role', role: 'motorLeft' }, args: [arith('-', lineRaw('lineLeft'), lineRaw('lineRight'))], blockId: id() };
    const lines = setupOf(uno([tone, motor]));
    expect(lines.filter((line) => /^ {2}(long|bool) _s/.test(line))).toEqual(['  long _s1;', '  long _s2;', '  long _s3;', '  long _s4;']);
    expect(lines.slice(-2)).toEqual([
      `  (_s1 = (long)millis(), _s2 = (long)analogRead(${L}), buzzerTone(BUZZER_PIN, sub32(x, _s1), _s2));`,
      `  motorSet(MOTOR_LEFT_EN, MOTOR_LEFT_IN1, MOTOR_LEFT_IN2, (_s3 = (long)analogRead(${L}), _s4 = (long)analogRead(${R}), sub32(_s3, _s4)));`,
    ]);
  });

  it('leaves one read as it is, and keeps && and || native: sequenced, skipping their right side as the simulator does', () => {
    expect(setupOf(uno([printIt(arith('-', lineRaw('lineLeft'), x())), printIt(logic('and', dark('lineLeft'), dark('lineRight'))), printIt(logic('or', compare('<', lineRaw('lineLeft'), int(5)), dark('lineRight')))])).slice(1)).toEqual([
      `  pinMode(${L}, INPUT);`,
      `  pinMode(${R}, INPUT);`,
      `  Serial.println(sub32((long)analogRead(${L}), x));`,
      `  Serial.println(((digitalRead(${L}) == HIGH) && (digitalRead(${R}) == HIGH)));`,
      `  Serial.println((((long)analogRead(${L}) < 5L) || (digitalRead(${R}) == HIGH)));`,
    ]);
  });

  it('hoists an && or || that reads whole (a bool temporary), and sequences inside its operands on their own', () => {
    const whole = compare('==', logic('and', dark('lineLeft'), dark('lineCenter')), dark('lineRight'));
    const inside = logic('and', compare('<', lineRaw('lineLeft'), lineRaw('lineRight')), dark('lineCenter'));
    expect(setupOf(uno([printIt(whole), printIt(inside)])).slice(1)).toEqual([
      `  pinMode(${L}, INPUT);`,
      '  pinMode(LINE_CENTER_PIN, INPUT);',
      `  pinMode(${R}, INPUT);`,
      '  bool _s1;',
      '  bool _s2;',
      '  long _s3;',
      '  long _s4;',
      `  Serial.println((_s1 = ((digitalRead(${L}) == HIGH) && (digitalRead(LINE_CENTER_PIN) == HIGH)), _s2 = (digitalRead(${R}) == HIGH), (_s1 == _s2)));`,
      `  Serial.println(((_s3 = (long)analogRead(${L}), _s4 = (long)analogRead(${R}), (_s3 < _s4)) && (digitalRead(LINE_CENTER_PIN) == HIGH)));`,
    ]);
  });

  it('re-evaluates a while condition every time, with loop()’s own temporaries; a join’s parts are printed one by one', () => {
    const loopWhile: YbcStatement = { kind: 'while', condition: compare('<', lineRaw('lineLeft'), lineRaw('lineRight')), body: [], blockId: id() };
    const generated = ok(generateUnoSketch(uno([printIt({ blockId: id(), type: 'str', kind: 'join', parts: [lineRaw('lineLeft'), lineRaw('lineRight')] })], [loopWhile]), { kit, board }));
    expect(bodyOf(generated.source, 'setup').slice(1)).toEqual([`  Serial.print((long)analogRead(${L}));`, `  Serial.println((long)analogRead(${R}));`]);
    expect(bodyOf(generated.source, 'loop')).toEqual(['  long _s1;', '  long _s2;', `  while ((_s1 = (long)analogRead(${L}), _s2 = (long)analogRead(${R}), (_s1 < _s2))) {`, '  }']);
  });

  it('keeps the line map on the code: the temporaries’ declarations belong to no block', () => {
    const sub = arith('-', lineRaw('lineLeft'), lineRaw('lineRight'));
    const statement = printIt(sub);
    const generated = ok(generateUnoSketch(uno([statement]), { kit, board }));
    const all = lines(generated.source);
    const range = generated.lineMap.find((entry) => entry.blockId === statement.blockId);
    expect(range && all[range.from - 1]).toBe(`  Serial.println((_s1 = (long)analogRead(${L}), _s2 = (long)analogRead(${R}), sub32(_s1, _s2)));`);
    expect(generated.lineMap.every((entry) => !/^ {2}(long|bool) _s\d+;$/.test(all[entry.from - 1] ?? ''))).toBe(true);
  });
});

describe('what the generator cannot say faithfully is a diagnostic (K4)', () => {
  it('refuses an IR that is not of the UNO family', () => {
    const message = 'A sketch is written for a program of the UNO family (32-bit numbers, no pause after a forever iteration).';
    expect(failure({ onStart: [], forever: null, variables: [] })).toEqual([{ code: 'unsupported-node', message }]);
    expect(failure(uno([], null, { loopPauseUs: 10_000 }))).toEqual([{ code: 'unsupported-node', message }]);
  });

  it('refuses a kit of another board, and a role or op the kit lacks', () => {
    expect(failure(uno([]), { kit: { ...kit, board: 'mega' } })).toEqual([{ code: 'capability-unavailable', message: 'The kit ref-uno-rover@0 is for the board mega, not uno-r3.' }]);
    const raw = structuredClone(refUnoRoverJson) as unknown as { id: string; ports: { id: string }[]; modules: { role: string; port: string }[] };
    raw.id = 'no-servo';
    raw.modules = raw.modules.filter((module) => module.role !== 'servo1');
    raw.ports = raw.ports.filter((port) => port.id !== 'SV1');
    const noServo = createKitCatalog([raw], [unoR3Board]).get({ id: 'no-servo', version: '0' }) as Kit;
    const servo: YbcStatement = { kind: 'call', op: 'servo.set', operand: { kind: 'role', role: 'servo1' }, args: [int(10)], blockId: 'sv' };
    expect(failure(uno([servo]), { kit: noServo })).toEqual([{ code: 'capability-unavailable', message: `The kit ${kitKey(noServo)} has no "servo.set" on servo1.` }]);
    const rawRead: Expr = { blockId: 'r', type: 'int', kind: 'read', op: 'analogIn.read', operand: { kind: 'pin', pin: 'D7' }, args: [] };
    expect(failure(uno([printIt(rawRead)]))).toEqual([{ code: 'capability-unavailable', message: 'D7 is not an analog input of uno-r3.' }]);
  });

  it('refuses a literal outside int32, a text outside print, an unknown variable and a mismatched type', () => {
    expect(failure(uno([printIt(int(2_147_483_648))]))).toEqual([{ code: 'value-out-of-range', message: 'A number must be between -2147483648 and 2147483647.' }]);
    expect(failure(uno([printIt(int(1.5))]))).toEqual([{ code: 'invalid-literal', message: 'A number must be a whole number.' }]);
    expect(failure(uno([{ kind: 'set', variable: 'x', value: str('a'), blockId: 's' }]))).toEqual([
      { code: 'type-mismatch', message: 'A variable must be a whole number, not str.' },
      { code: 'unsupported-node', message: 'A text can only be printed on this board.' },
    ]);
    expect(failure(uno([printIt({ blockId: 'v', type: 'int', kind: 'variable', variable: 'nope' })]))).toEqual([{ code: 'unknown-variable', message: 'The variable "nope" is not declared.' }]);
    expect(failure(uno([printIt(str('a\tb'))]))).toEqual([{ code: 'invalid-literal', message: 'A text cannot contain control characters or a lone surrogate.' }]);
  });

  it('refuses a count up it cannot write: a step other than 1, an end above 2147483646, a typed-in descending range', () => {
    const countUp = (from: number, to: number, step = 1): YbcStatement => ({ kind: 'countUp', variable: 'x', from: int(from), to: int(to), step, body: [], blockId: 'c' });
    expect(failure(uno([countUp(0, 5, 2)]))).toEqual([{ code: 'value-out-of-range', message: '"count up" counts by 1 on this board.' }]);
    expect(failure(uno([countUp(0, 2_147_483_647)]))).toEqual([{ code: 'value-out-of-range', message: 'The end of "count up" is at most 2147483646.' }]);
    expect(failure(uno([countUp(5, 1)]))).toEqual([{ code: 'descending-range-not-supported', message: '"count up" cannot count down.' }]);
    expect(failure(uno([{ kind: 'waitMs', ms: int(60_001), blockId: 'w' }]))).toEqual([{ code: 'value-out-of-range', message: 'A wait is 0 to 60000 milliseconds.' }]);
  });

  it('refuses the Yolo:Bit’s onboard parts and header pins', () => {
    const show: YbcStatement = { kind: 'call', op: 'display.clear', blockId: 'd' };
    const header: YbcStatement = { kind: 'call', op: 'digital.write', args: [int(0), int(1)], blockId: 'p' };
    const light: Expr = { blockId: 'l', type: 'int', kind: 'read', op: 'light.level' };
    expect(failure(uno([show, header, printIt(light)]))).toEqual([
      { code: 'unsupported-node', message: 'The generator does not know this kind of block.' },
      { code: 'unsupported-node', message: 'The generator does not know this kind of block.' },
      { code: 'unsupported-node', message: 'The generator does not know this kind of value.' },
    ]);
  });

  it('stops at the nesting limits and at the size limit, with no source', () => {
    let deep: Expr = int(1);
    for (let level = 0; level < MAX_EXPRESSION_DEPTH; level += 1) {
      deep = { blockId: id(), type: 'int', kind: 'arith', op: '+', left: int(1), right: deep };
    }
    expect(failure(uno([printIt(deep)]))).toEqual([{ code: 'limit-exceeded', message: `An expression can be nested at most ${MAX_EXPRESSION_DEPTH} levels deep.` }]);
    let nested: YbcStatement = printIt(int(1));
    for (let level = 0; level < MAX_STATEMENT_DEPTH; level += 1) {
      nested = { kind: 'while', condition: { blockId: id(), type: 'bool', kind: 'bool', value: false }, body: [nested], blockId: id() };
    }
    expect(failure(uno([nested]))).toEqual([{ code: 'limit-exceeded', message: `Blocks can be nested at most ${MAX_STATEMENT_DEPTH} levels deep.` }]);
    // A repeat indents its body twice but nests it once: the limit counts blocks.
    let repeats: YbcStatement = printIt(int(1));
    for (let level = 1; level < MAX_STATEMENT_DEPTH; level += 1) {
      repeats = { kind: 'repeat', times: int(1), body: [repeats], blockId: id() };
    }
    expect(generateUnoSketch(uno([repeats]), { kit, board }).ok).toBe(true);
    expect(failure(uno([{ kind: 'repeat', times: int(1), body: [repeats], blockId: id() }]))).toEqual([{ code: 'limit-exceeded', message: `Blocks can be nested at most ${MAX_STATEMENT_DEPTH} levels deep.` }]);
    const big = Array.from({ length: Math.ceil(MAX_GENERATED_BYTES / 1000) }, () => printIt(str('a'.repeat(1000))));
    expect(failure(uno(big))).toEqual([{ code: 'program-too-large', message: `The generated sketch is limited to ${MAX_GENERATED_BYTES} bytes.` }]);
    expect(generateUnoSketch(uno(big.slice(0, 200)), { kit, board }).ok).toBe(true);
  });
});
