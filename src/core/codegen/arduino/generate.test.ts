// N18 C1: what the Arduino generator writes for a robot program, beyond the goldens: the fixed order of the sketch and its header, the
// setup() lines, the helpers and libraries a program needs and no more, the line map, and the diagnostics of what it cannot say.

const sketch = (onStart: Parameters<typeof compileCase>[0]['onStart'], forever?: Parameters<typeof compileCase>[0]['forever'], variables: [string, string][] = [['x', 'x']]) => {
  const { ir } = compileCase({ profile: 'uno-advanced', onStart, ...(forever ? { forever } : {}), variables });
  return ok(generateUnoSketch(ir, { kit, board }));
};

function ok(result: UnoSketchResult): Extract<UnoSketchResult, { ok: true }> {
  if (!result.ok) {
    throw new Error(JSON.stringify(result.diagnostics));
  }
  return result;
}

const lines = (source: string) => source.split('\n');
/** The lines inside `void <name>() {` … `}`. */
const bodyOf = (source: string, name: 'setup' | 'loop') => {
  const all = lines(source);
  const start = all.indexOf(`void ${name}() {`);
  return all.slice(start + 1, all.indexOf('}', start));
};

let blockCounter = 0;
const id = () => `b${String(++blockCounter)}`;
const int = (value: number): Expr => ({ blockId: id(), type: 'int', kind: 'int', value });
const str = (value: string): Expr => ({ blockId: id(), type: 'str', kind: 'str', value });
const printIt = (value: Expr): YbcStatement => ({ kind: 'print', value, blockId: id() });
const uno = (onStart: YbcStatement[], forever: YbcStatement[] | null = null, extra: Partial<YbcProgramIR> = {}): YbcProgramIR => ({
  onStart,
  forever,
  variables: [{ id: 'x', name: 'x', type: 'int' }],
  numeric: 'cxx-int32',
  loopPauseUs: 0,
  ...extra,
});
const failure = (ir: YbcProgramIR, options: Partial<Parameters<typeof generateUnoSketch>[1]> = {}) => {
  const result = generateUnoSketch(ir, { kit, board, ...options });
  return result.ok ? [] : result.diagnostics.map(({ code, message }) => ({ code, message }));
};

describe('the order of a sketch (contract §2.1)', () => {
  it('is header, includes, defines, globals, helpers, setup(), loop(), one blank line apart', () => {
    const { source } = sketch([servoSet('servo1', num(30)), setVar('x', add(getVar('x'), num(1)))], [wait(num(10))]);
    const starts = ['// Scenario:', '#include <Servo.h>', '#define SERVO1_PIN 9', 'Servo servo1;', 'long add32(', 'void servoSet(', 'void setup() {', 'void loop() {'].map((head) =>
      lines(source).findIndex((line) => line.startsWith(head)),
    );
    expect(starts.every((index) => index >= 0)).toBe(true);
    expect([...starts].sort((a, b) => a - b)).toEqual(starts);
    expect(source).toContain('Servo servo1;\nlong x = 0L;\n\nlong add32(');
    expect(source.endsWith('void loop() {\n  delay(10L);\n}\n')).toBe(true);
  });

  it('names the scenario, the kit and the board, says it is generated, and lists the libraries', () => {
    const { ir } = compileCase({ profile: 'uno-basic', onStart: [servoSet('servo1', num(30))], variables: [] });
    const { source, libraries } = ok(generateUnoSketch(ir, { kit, board, scenario: { key: 'rb-servo-gate', version: 2 } }));
    expect(lines(source).slice(0, 3)).toEqual([
      '// Scenario: rb-servo-gate@2, kit: ref-uno-rover@0, board: uno-r3@0',
      '// Generated by STEM Studio from the blocks: editing this code does not change the lab.',
      '// Target: arduino:avr:uno, contract uno-arduino-avr 0.1.7. Libraries: arduino:avr@1.8.8 (LGPL-2.1), Servo@1.3.0 (LGPL-2.1)',
    ]);
    expect(libraries).toEqual([
      { name: 'arduino:avr', version: '1.8.8', license: 'LGPL-2.1' },
      { name: 'Servo', version: '1.3.0', license: 'LGPL-2.1' },
    ]);
  });

  it('writes no text of a kit or scenario into the header that could end the comment or join the next line', () => {
    const odd: Kit = { ...kit, id: 'odd\nkit\\', version: '0' };
    const { source } = ok(generateUnoSketch(uno([]), { kit: odd, board, scenario: { key: 'a*/b c', version: 1 } }));
    expect(lines(source)[0]).toBe('// Scenario: a*/b_c@1, kit: odd_kit_@0, board: uno-r3@0');
    expect(lines(source)[2]).toBe('// Target: arduino:avr:uno, contract uno-arduino-avr 0.1.7. Libraries: arduino:avr@1.8.8 (LGPL-2.1)');
  });

  it('is the same text for the same program', () => {
    const blocks = [print(text('a')), motorSet('motorLeft', num(20))];
    expect(sketch(blocks).source).toBe(sketch(blocks).source);
  });
});

