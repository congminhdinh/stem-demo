import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, describe, expect, it } from 'vitest';
import { sketchCases } from './__fixtures__/sketch-cases';

// N18 C1: scripts/check-arduino.mjs (`pnpm check:arduino`, L2) decides PASS, FAIL and PENDING as the brief says. The real compile is
// not part of `pnpm verify` (it takes the pinned toolchain and ~15 s); these tests run the script against a stand-in arduino-cli (a
// POSIX shell script, so they are skipped on Windows) that answers as arduino-cli 1.5.1 does, to prove the decisions: no toolchain or
// another version is PENDING and never a pass, --require makes PENDING a failure, a warning of the sketch (not of the core), RAM above
// 75 %, a compile error and a GPL library fail, and a missing library is installed at its version. It checks nothing about a board.

type Report = {
  status: 'pass' | 'fail' | 'pending';
  reason: string | null;
  files: number;
  results: { file: string; status: string; problems: string[]; ramBytes: number | null; ramPercent: number | null; flashBytes: number | null; libraries: string[] }[];
};

const nl = String.fromCharCode(10);
const stub = [
  '#!/bin/sh',
  'case "$1" in',
  '  version) echo "arduino-cli  Version: ${STUB_VERSION:-1.5.1} Commit: stub Date: 2026-06-05"; exit 0;;',
  `  core) echo '{"platforms":[{"id":"arduino:avr","installed_version":"1.8.8"}]}'; exit 0;;`,
  '  lib)',
  // `lib list` alone gives the user's libraries; `--all` adds the ones the core ships (Wire 1.0 of arduino:avr 1.8.8, location platform).
  `    if [ "$2" = "list" ] && [ "$3" = "--all" ]; then echo '{"installed_libraries":[{"library":{"name":"Wire","version":"1.0","location":"platform"}},{"library":{"name":"Servo","version":"1.3.0","location":"user"}}]}'; exit 0; fi`,
  `    if [ "$2" = "list" ]; then echo '{"installed_libraries":[{"library":{"name":"Servo","version":"1.3.0","location":"user"}}]}'; exit 0; fi`,
  '    if [ "$2" = "install" ]; then echo "$3" >> "$STUB_LOG"; exit 0; fi;;',
  '  compile)',
  '    for last; do :; done',
  '    name=$(basename "$last"); file="$last/$name.ino"',
  `    if grep -q STUB_ERROR "$file"; then echo "$file:2:3: error: 'nope' was not declared in this scope"; echo "Error during build: exit status 1"; exit 1; fi`,
  `    if grep -q STUB_WARNING "$file"; then echo "$file:3:7: warning: unused variable 'y' [-Wunused-variable]"; fi`,
  `    echo "/cores/arduino/new.cpp:59:60: warning: unused parameter 'tag' [-Wunused-parameter]"`,
  `    ram=$(sed -n 's/.*STUB_RAM=\\([0-9]*\\).*/\\1/p' "$file"); ram=\${ram:-9}`,
  '    echo "Sketch uses 444 bytes (1%) of program storage space. Maximum is 32256 bytes."',
  '    echo "Global variables use $ram bytes (0%) of dynamic memory, leaving 100 bytes for local variables. Maximum is 2048 bytes."',
  '    exit 0;;',
  'esac',
  'exit 1',
  '',
].join(nl);

const dir = mkdtempSync(join(tmpdir(), 'arduino-stub-'));
const cli = join(dir, 'arduino-cli');
const installs = join(dir, 'installs.log');
writeFileSync(cli, stub, { mode: 0o755 });
afterAll(() => rmSync(dir, { recursive: true, force: true }));

const header = (libraries = 'arduino:avr@1.8.8 (LGPL-2.1)') =>
  ['// Scenario: none, kit: ref-uno-rover@0, board: uno-r3@0', '// Generated by STEM Studio from the blocks: editing this code does not change the lab.', `// Target: arduino:avr:uno, contract uno-arduino-avr 0.1.2. Libraries: ${libraries}`].join(nl);

function sketchDir(files: Record<string, string>): string {
  const target = mkdtempSync(join(dir, 'sketches-'));
  for (const [name, body] of Object.entries(files)) {
    writeFileSync(join(target, `${name}.ino`), `${body}${nl}void setup() {${nl}}${nl}void loop() {${nl}}${nl}`);
  }
  return target;
}

const check = (targets: string[], options: { cli?: string; env?: Record<string, string>; flags?: string[] } = {}) => {
  const result = spawnSync(process.execPath, ['scripts/check-arduino.mjs', '--json', ...(options.flags ?? []), ...targets], {
    encoding: 'utf8',
    timeout: 60_000,
    env: { ...process.env, ARDUINO_CLI: options.cli ?? cli, STUB_LOG: installs, ...options.env },
  });
  return { report: JSON.parse(result.stdout) as Report, exit: result.status };
};

describe.skipIf(process.platform === 'win32')('pnpm check:arduino (stand-in arduino-cli)', () => {
  it('is PENDING, never PASS, without arduino-cli or with another version; --require makes it a failure', () => {
    const sketches = sketchDir({ ok: header() });
    const none = check([sketches], { cli: join(dir, 'no-such-cli') });
    expect(none).toEqual({ report: { status: 'pending', reason: 'arduino-cli is not on PATH', toolchain: null, files: 1, results: [] }, exit: 0 });
    expect(check([sketches], { cli: join(dir, 'no-such-cli'), flags: ['--require'] }).exit).toBe(2);
    const other = check([sketches], { env: { STUB_VERSION: '1.4.0' } });
    expect(other.report).toMatchObject({ status: 'pending', reason: 'arduino-cli is 1.4.0, the contract pins 1.5.1' });
  });

  it('never passes when it compiles nothing: no sketch is PENDING, and a FAIL under --require, with or without the toolchain', () => {
    const empty = mkdtempSync(join(dir, 'empty-'));
    const reason = 'no sketch to compile (no __golden__/*.ino, or none in the files and folders given)';
    expect(check([empty])).toEqual({ report: { status: 'pending', reason, toolchain: null, files: 0, results: [] }, exit: 0 });
    expect(check([empty], { flags: ['--require'] })).toEqual({ report: { status: 'fail', reason, toolchain: null, files: 0, results: [] }, exit: 1 });
    expect(check([empty], { cli: join(dir, 'no-such-cli'), flags: ['--require'] })).toMatchObject({ report: { status: 'fail', reason }, exit: 1 });
  });

  it('passes a sketch that compiles with no warning of its own, and reports its sizes', () => {
    const { report, exit } = check([sketchDir({ ok: header() })], { flags: ['--require'] });
    expect(exit).toBe(0);
    expect(report.status).toBe('pass');
    expect(report.results).toEqual([
      expect.objectContaining({ status: 'pass', problems: [], flashBytes: 444, ramBytes: 9, ramPercent: 0.44, libraries: ['arduino:avr@1.8.8'] }),
    ]);
  });

  it('fails on a warning of the sketch, on RAM above 75 %, on a compile error and on a GPL library', () => {
    const { report, exit } = check([
      sketchDir({
        warning: `${header()}${nl}// STUB_WARNING`,
        ram1536: `${header()}${nl}// STUB_RAM=1536`,
        ram1537: `${header()}${nl}// STUB_RAM=1537`,
        error: `${header()}${nl}// STUB_ERROR`,
        gpl: header('arduino:avr@1.8.8 (LGPL-2.1), Foo@1.0.0 (GPL-3.0)'),
        unnamed: '// no header',
      }),
    ]);
    expect(exit).toBe(1);
    expect(report.status).toBe('fail');
    const byName = Object.fromEntries(report.results.map((result) => [result.file.replace(/^.*\//, ''), result]));
    expect(byName['warning.ino']?.problems).toEqual(["warning: unused variable 'y' [-Wunused-variable]"]);
    expect(byName['ram1536.ino']).toMatchObject({ status: 'pass', ramPercent: 75 });
    expect(byName['ram1537.ino']).toMatchObject({ status: 'fail', problems: ['uses 75.05 % of the RAM (1537 of 2048 B), above 75 %'] });
    expect(byName['error.ino']?.problems).toEqual([expect.stringMatching(/^does not compile: .*error: 'nope' was not declared in this scope \| Error during build: exit status 1$/)]);
    expect(byName['gpl.ino']?.problems).toEqual(['Foo@1.0.0 is GPL-3.0: a generated sketch uses no GPL library']);
    expect(byName['unnamed.ino']?.problems).toEqual(['the header names no libraries (a generated sketch says "Libraries: …")']);
  });

  it('installs a library the sketch names at its exact version when it is missing, and not when it is there', () => {
    const { report } = check([sketchDir({ servo: header('arduino:avr@1.8.8 (LGPL-2.1), Servo@1.3.0 (LGPL-2.1), Other@2.0.1 (MIT)') })]);
    expect(report.status).toBe('pass');
    expect(readFileSync(installs, 'utf8')).toBe(`Other@2.0.1${nl}`);
  });

  it('counts a library the core ships (Wire 1.0 of arduino:avr 1.8.8) as installed: it never asks to install it (N19 A3, review I1)', () => {
    const before = readFileSync(installs, 'utf8');
    const { report } = check([sketchDir({ colour: header('arduino:avr@1.8.8 (LGPL-2.1), Servo@1.3.0 (LGPL-2.1), Wire@1.0 (LGPL-2.1)') })], { flags: ['--require'] });
    expect(report.status).toBe('pass');
    expect(report.results).toEqual([expect.objectContaining({ status: 'pass', problems: [], libraries: ['arduino:avr@1.8.8', 'Servo@1.3.0', 'Wire@1.0'] })]);
    expect(readFileSync(installs, 'utf8')).toBe(before);
  });

  it('finds every golden sketch of the repository by default', () => {
    expect(check([]).report).toMatchObject({ status: 'pass', files: sketchCases.length });
  });
});
